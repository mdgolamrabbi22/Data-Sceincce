marks = int(input("Enter Your Marks :"))
    
if marks > 80:
    print("You are A+")
elif marks > 70:
    print("You are A")
elif marks > 60:
    print("You are B")
elif marks > 50:
    print("You are C")
elif marks > 40:
    print("You are D")
elif marks >= 33 :
    print("You are Passed.")
else:
    print("You are Fail.")